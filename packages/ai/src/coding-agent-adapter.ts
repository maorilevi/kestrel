import type { ArchitectureGraph, ArchitectureNode } from '@kestrel/core';

/**
 * Integration point for AI coding agents.
 *
 * The core architecture engine never imports this file; agents consume the
 * architecture graph, not the other way around. That keeps Claude specific
 * logic out of the model and leaves room for other agents (CLI, CI, GitHub).
 */
export interface CodingAgentAdapter {
  /** Stable identifier, e.g. `claude-code`. */
  readonly id: string;
  /** Human readable name shown in the UI. */
  readonly label: string;

  askAboutNode(node: ArchitectureNode, graph: ArchitectureGraph, prompt: string): Promise<void>;

  /** Multi-selection is already part of the contract; the MVP passes one node. */
  askAboutNodes?(nodes: ArchitectureNode[], graph: ArchitectureGraph, prompt: string): Promise<void>;
}

/**
 * Renders the architectural context for a selection as markdown.
 *
 * Deliberately framework free so the same context can later be sent to a
 * terminal, a chat participant, a CLI or a CI check.
 */
export function buildAgentContext(
  nodes: readonly ArchitectureNode[],
  graph: ArchitectureGraph,
  prompt: string,
): string {
  const byId = new Map(graph.nodes.map((node) => [node.id, node]));
  const nameOf = (id: string): string => byId.get(id)?.name ?? id;
  const lines: string[] = [];

  lines.push(prompt.trim().length > 0 ? prompt.trim() : 'Explain this part of the architecture.');
  lines.push('');
  lines.push('## Architectural context (generated by KESTREL)');
  lines.push('');

  for (const node of nodes) {
    lines.push(`### ${node.name} (${node.type})`);
    if (node.filePath) {
      lines.push(`- File: \`${node.filePath}\``);
    }
    if (node.parentId) {
      lines.push(`- Module: ${nameOf(node.parentId)}`);
    }

    const dependencies = graph.edges
      .filter((edge) => edge.source === node.id && (edge.type === 'injects' || edge.type === 'imports'))
      .map((edge) => nameOf(edge.target));
    if (dependencies.length > 0) {
      lines.push(`- Depends on: ${dependencies.join(', ')}`);
    }

    const dependents = graph.edges
      .filter((edge) => edge.target === node.id && (edge.type === 'injects' || edge.type === 'imports'))
      .map((edge) => nameOf(edge.source));
    if (dependents.length > 0) {
      lines.push(`- Used by: ${dependents.join(', ')}`);
    }

    const children = graph.edges
      .filter((edge) => edge.source === node.id && edge.type === 'contains')
      .map((edge) => nameOf(edge.target));
    if (children.length > 0) {
      lines.push(`- Contains: ${children.join(', ')}`);
    }

    lines.push('');
  }

  const files = nodes.map((node) => node.filePath).filter((value): value is string => Boolean(value));
  if (files.length > 0) {
    lines.push('## Relevant files');
    lines.push('');
    for (const file of files) {
      lines.push(`- ${file}`);
    }
    lines.push('');
  }

  return lines.join('\n');
}
